import { test,expect } from '@playwright/test';
test('owner previews exact HTML, explicitly authorizes download, archives, and sees deletion completion',async({page})=>{
 await page.goto('/');await page.getByRole('checkbox',{name:/I understand the fictional sample/}).check();await page.getByRole('button',{name:'Open sample household'}).click();
 await page.getByRole('button',{name:'History',exact:true}).click();
 const records=page.getByRole('region',{name:'Private records'});
 await expect(records.getByRole('button',{name:'Prepare private preview'})).toBeEnabled();
 await records.getByLabel('File format').selectOption('html');
 await records.getByRole('button',{name:'Prepare private preview'}).click();
 await expect(records.getByLabel('Exact file content')).toContainText('Denlumi private factual record');
 await expect(records.getByRole('button',{name:'Authorize private export'})).toBeDisabled();
 await records.getByLabel(/I reviewed this exact content/).check();
 await records.getByRole('button',{name:'Authorize private export'}).click();
 await expect(records.getByRole('button',{name:'Download private file'})).toBeVisible();
 const downloaded=page.waitForEvent('download');await records.getByRole('button',{name:'Download private file'}).click();
 expect((await downloaded).suggestedFilename()).toMatch(/\.html$/);
 await records.getByText('Archive a pet, keeping history',{exact:true}).click();
 const pet=records.getByRole('combobox',{name:'Pet',exact:true});
 const option=await pet.locator('option').nth(1).getAttribute('value');
 await pet.selectOption(option!);await records.getByLabel('Archive the selected pet and retain their history.').check();
 await records.getByRole('button',{name:'Archive selected pet'}).click();
 await expect(records.getByText(/was archived. Attributed history is retained/)).toBeVisible();
 await records.getByText('Delete the whole household',{exact:true}).click();
 const confirm=records.getByLabel(/Type “.*” to confirm/);const label=await confirm.locator('..').textContent();
 await confirm.fill(label!.match(/Type “(.*)” to confirm/)![1]);
 await records.getByLabel(/I request deletion of this entire household/).check();
 await records.getByRole('button',{name:'Disable household and request deletion'}).click();
 await expect(records.getByRole('heading',{name:'Household deletion: pending'})).toBeVisible();
 await expect(page.getByRole('heading',{name:'Guidance is paused.'})).not.toBeVisible();
 await records.getByRole('button',{name:'Run local primary cleanup'}).click();
 await expect(records.getByRole('heading',{name:'Household deletion: completed'})).toBeVisible();
 await expect(records.getByText('Primary database cleanup: verified by the server.')).toBeVisible();
});
