test('synthetic microphone PCM upload yields review-only transcript; offline Stop closes live capture',async({page,context})=>{
 await page.clock.install();
 let uploads=0;
 // Only the speech provider response is mocked. Auth, household and MCP remain real local calls.
 await page.route('**/api/transcription',async route=>{uploads++;const req=route.request();expect(req.headers()['content-type']).toBe('audio/pcm;rate=16000;channels=1');expect(req.postDataBuffer()!.length).toBeGreaterThan(3200);expect(req.postDataBuffer()!.length).toBeLessThanOrEqual(480000);await route.fulfill({json:{transcript:'Nora did not chase Finn.',source_kind:'voice',saved:false}});});
 await enter(page);await page.getByRole('button',{name:'Record a check-in',exact:true}).click();
 await expect(page.getByRole('button',{name:'Finish recording'})).toHaveAttribute('aria-pressed','true');
 await page.waitForTimeout(350);
 await page.getByRole('button',{name:'Finish recording'}).click();
 await expect(page.getByLabel('Your check-in',{exact:true})).toHaveValue('Nora did not chase Finn.');
 await expect(page.getByText('Transcript ready. Review the words before continuing.')).toBeVisible();expect(uploads).toBe(1);
 await page.getByRole('button',{name:'Continue',exact:true}).click();
 await page.getByRole('button',{name:'Review identities, meaning and timing in report form'}).click();
 await expect(page.getByLabel('The exact fictional report')).toHaveValue('Nora did not chase Finn.');
 await page.clock.fastForward(14*60*1000);
 await page.getByRole('button',{name:'Record a check-in',exact:true}).click();
 await expect(page.getByRole('button',{name:'Finish recording'})).toBeVisible();
 await page.waitForTimeout(350);await page.getByRole('button',{name:'Finish recording'}).click();
 await expect(page.getByText('Transcript ready. Review the words before continuing.')).toBeVisible();expect(uploads).toBe(2);
 await page.clock.fastForward(61*1000);
 await expect(page.getByLabel('The exact fictional report')).toHaveValue('');
 await expect(page.getByLabel('Your check-in',{exact:true})).toHaveValue('');
 await page.getByRole('button',{name:'Record a check-in',exact:true}).click();
 await expect(page.getByRole('button',{name:'Finish recording'})).toBeVisible();await context.setOffline(true);
 await page.getByRole('button',{name:'Stop guidance',exact:true}).click();
 await expect(page.getByText('Stopped on this device.',{exact:true})).toBeVisible();
 await expect(page.getByRole('button',{name:'Record a check-in',exact:true})).toHaveAttribute('aria-pressed','false');
 expect(uploads).toBe(2);await context.setOffline(false);
});
