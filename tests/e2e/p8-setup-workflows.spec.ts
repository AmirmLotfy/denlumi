test('W01 read outage hides setup writes and retry restores the current household',async({page,context})=>{
 const home=await testHousehold('single_dog');
 await context.addCookies([{name:'denlumi_session',value:home.owner.token,url:'http://127.0.0.1:3400',httpOnly:true,sameSite:'Strict'}]);
 await page.route('**/api/households/*/graph',route=>route.fulfill({status:503,json:{error:'SERVICE_UNAVAILABLE'}}));
 await page.goto('/household');await expect(page.getByRole('alert').filter({hasText:'Current household records unavailable'})).toBeVisible();
 await expect(page.getByRole('button',{name:'Save pet',exact:true})).toHaveCount(0);
 await page.unroute('**/api/households/*/graph');await page.getByRole('button',{name:'Retrieve household records again'}).click();
 await expect(page.getByText('Finn · dog',{exact:true})).toBeVisible();
});
